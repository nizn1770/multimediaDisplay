#!/usr/bin/env bash
# Pi TV Display installer. Safe to re-run (idempotent).
# Usage: ./install.sh [--dry-run]     PITV_USER / PITV_BRANCH env vars override defaults.
set -euo pipefail
DRY=0; [ "${1:-}" = "--dry-run" ] && DRY=1
DIR="$(cd "$(dirname "$0")" && pwd)"
USER_NAME="${PITV_USER:-$(id -un)}"
HOME_DIR="$(getent passwd "$USER_NAME" | cut -d: -f6)"; HOME_DIR="${HOME_DIR:-$HOME}"
BRANCH="${PITV_BRANCH:-main}"
REMOTE_URL="${PITV_REMOTE_URL:-https://github.com/nizn1770/multimediaDisplay.git}"
run() { if [ "$DRY" = 1 ]; then echo "+ $*"; else "$@"; fi; }
say() { printf '\n==> %s\n' "$*"; }
# write_file DEST MODE (content on stdin); uses sudo when DEST is outside $HOME
write_file() {
  local dest="$1" mode="$2" tmp; tmp="$(mktemp)"; cat >"$tmp"
  if [ "$DRY" = 1 ]; then echo "+ write $dest (mode $mode):"; sed 's/^/    /' "$tmp"; rm -f "$tmp"; return; fi
  if [ -f "$dest" ] && cmp -s "$tmp" "$dest"; then rm -f "$tmp"; echo "unchanged: $dest"; return; fi
  case "$dest" in "$HOME_DIR"/*) install -D -m "$mode" "$tmp" "$dest" ;; *) sudo install -D -m "$mode" "$tmp" "$dest" ;; esac
  rm -f "$tmp"; echo "wrote: $dest"
}

[ "$(id -u)" -eq 0 ] && { echo "Run as your normal user (e.g. pi), not root; sudo is used where needed." >&2; exit 1; }
[ "$DRY" = 1 ] && echo "DRY RUN: nothing will be changed"

say "Installing system packages"
PKGS="git python3-venv python3-pip curl chromium xserver-xorg x11-xserver-utils xinit openbox unclutter cec-utils"
if command -v apt-get >/dev/null; then
  # Trixie (and current Bookworm) name it "chromium"; older images used "chromium-browser".
  if ! apt-cache show chromium >/dev/null 2>&1; then PKGS="${PKGS/chromium/chromium-browser}"; fi
  run sudo apt-get update -q
  # shellcheck disable=SC2086
  run sudo apt-get install -y -q $PKGS || run sudo apt-get install -y -q ${PKGS/ unclutter/}
else
  echo "apt-get not found; install manually: $PKGS"
fi

say "Python virtualenv"
[ -d "$DIR/.venv" ] || run python3 -m venv "$DIR/.venv"
run "$DIR/.venv/bin/pip" install -q --upgrade pip
run "$DIR/.venv/bin/pip" install -q -r "$DIR/requirements.txt"

say "Local config"
if [ -f "$DIR/config.local.yaml" ]; then echo "keeping existing config.local.yaml"
else run cp "$DIR/config.example.yaml" "$DIR/config.local.yaml"; run chmod 600 "$DIR/config.local.yaml"; fi
run mkdir -p "$DIR/secrets" "$DIR/cache/photos"; run chmod 700 "$DIR/secrets"

say "Git remote + hooks"
if git -C "$DIR" rev-parse >/dev/null 2>&1; then
  git -C "$DIR" remote get-url origin >/dev/null 2>&1 || run git -C "$DIR" remote add origin "$REMOTE_URL"
  run git -C "$DIR" config core.hooksPath scripts/hooks
fi

say "systemd services"
write_file /etc/systemd/system/pitv.service 644 <<UNIT
[Unit]
Description=Pi TV display server
After=network-online.target
Wants=network-online.target
[Service]
User=$USER_NAME
WorkingDirectory=$DIR
Environment=PITV_CONFIG=$DIR/config.local.yaml
Environment=DISPLAY=:0
ExecStart=$DIR/.venv/bin/python -m app.server
Restart=always
RestartSec=5
[Install]
WantedBy=multi-user.target
UNIT
write_file /etc/systemd/system/pitv-update.service 644 <<UNIT
[Unit]
Description=Pi TV auto-update (git pull + redeploy)
After=network-online.target
[Service]
Type=oneshot
User=$USER_NAME
WorkingDirectory=$DIR
Environment=PITV_BRANCH=$BRANCH PITV_REMOTE_URL=$REMOTE_URL
ExecStart=$DIR/scripts/update.sh
UNIT
write_file /etc/systemd/system/pitv-update.timer 644 < "$DIR/deploy/pitv-update.timer"
write_file /etc/sudoers.d/pitv 440 <<SUDO
$USER_NAME ALL=(root) NOPASSWD: /usr/bin/systemctl restart pitv.service, /bin/systemctl restart pitv.service
SUDO
if [ "$DRY" = 0 ]; then sudo visudo -cf /etc/sudoers.d/pitv >/dev/null || { sudo rm -f /etc/sudoers.d/pitv; echo "sudoers check failed" >&2; exit 1; }; fi
run sudo systemctl daemon-reload
run sudo systemctl enable --now pitv.service pitv-update.timer
run sudo systemctl restart pitv.service

say "Kiosk autostart (Raspberry Pi OS Lite: console autologin -> startx -> openbox -> Chromium)"
KIOSK="$DIR/scripts/kiosk.sh"
write_file "$HOME_DIR/.xinitrc" 644 <<XRC
#!/bin/sh
# Pi TV kiosk session (generated by install.sh)
xset s off; xset s noblank; xset -dpms
unclutter -idle 0.5 -root &
exec openbox-session
XRC
write_file "$HOME_DIR/.config/openbox/autostart" 755 <<OBX
# Pi TV kiosk (generated by install.sh)
$KIOSK &
OBX
# Use ~/.profile (creating ~/.bash_profile would make bash skip ~/.profile entirely).
PROFILE="$HOME_DIR/.profile"; MARK="# pitv-startx"
if [ -f "$HOME_DIR/.bash_profile" ] && grep -qF "$MARK" "$HOME_DIR/.bash_profile"; then
  echo "NOTE: old pitv snippet found in ~/.bash_profile (from an earlier install); remove it if ~/.profile isn't otherwise sourced."
fi
if [ -f "$PROFILE" ] && grep -qF "$MARK" "$PROFILE"; then echo "startx-on-login already set"
elif [ "$DRY" = 1 ]; then echo "+ append startx-on-tty1 snippet to $PROFILE"
else
  cat >>"$PROFILE" <<'PRO'
# pitv-startx: start the kiosk X session on the physical console only
if [ -z "${DISPLAY:-}" ] && [ "$(tty)" = /dev/tty1 ]; then exec startx -- -nocursor >/tmp/pitv-x.log 2>&1; fi
PRO
fi
if command -v raspi-config >/dev/null; then
  run sudo raspi-config nonint do_boot_behaviour B2   # console autologin (Lite)
fi

say "Done"
IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
cat <<MSG
Display server: http://127.0.0.1:$("$DIR/pitv" get server.port 2>/dev/null || echo 8080)   Settings (from phone/laptop on your Wi-Fi): http://${IP:-pitv.local}:$("$DIR/pitv" get server.port 2>/dev/null || echo 8080)/settings
Next: follow docs/SERVICE_ACCOUNT_SETUP.txt, edit config.local.yaml (mock: false), then: sudo systemctl restart pitv
Reboot once to start the kiosk browser:  sudo reboot
Performance tips for Pi 3B+ (swap, gpu_mem): docs/PI_SETUP.md
MSG
